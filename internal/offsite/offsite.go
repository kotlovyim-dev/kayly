// Package offsite copies backups to an S3-compatible bucket, encrypted with a recovery key
// the owner keeps off the server (ARCHITECTURE.md §8). Sync is convergent: it compares the
// backup directory with the bucket and uploads what is missing, so a crash or an outage
// only delays uploads.
package offsite

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"sync"
	"time"

	"github.com/kotlovyim-dev/kayly/internal/deploy"
)

const settingKey = "offsite"

// Config is where backups go. RecoveryKey is generated by Configure.
type Config struct {
	Endpoint    string `json:"endpoint"`
	Region      string `json:"region,omitempty"`
	Bucket      string `json:"bucket"`
	AccessKey   string `json:"access_key"`
	SecretKey   string `json:"secret_key"`
	RecoveryKey []byte `json:"recovery_key"`
}

// Settings is the part of the store a Manager needs.
type Settings interface {
	Setting(ctx context.Context, key string) (string, error)
	SetSetting(ctx context.Context, key, value string) error
}

// Manager uploads the backups under dir.
type Manager struct {
	settings Settings
	dir      string
	notify   func(ctx context.Context, text string)
	log      *slog.Logger
	// open connects to the bucket. Replaced in tests.
	open func(Config) (Bucket, error)
	now  func() time.Time

	mu      sync.Mutex // one sync at a time
	failing bool       // the last sync failed and the owner was told
	last    time.Time
	lastErr string
}

// New returns a Manager. notify may be nil.
func New(s Settings, dir string, notify func(context.Context, string), log *slog.Logger) *Manager {
	return &Manager{settings: s, dir: dir, notify: notify, log: log, open: OpenS3, now: time.Now}
}

func (m *Manager) config(ctx context.Context) (Config, bool, error) {
	raw, err := m.settings.Setting(ctx, settingKey)
	if err != nil || raw == "" {
		return Config{}, false, err
	}
	var c Config
	if err := json.Unmarshal([]byte(raw), &c); err != nil {
		return Config{}, false, fmt.Errorf("offsite: stored config: %w", err)
	}
	return c, true, nil
}

// Configure checks that the bucket accepts writes, then stores it. The first call
// generates the recovery key and returns it (base64); later calls keep the key and return
// "". The caller shows the key once.
func (m *Manager) Configure(ctx context.Context, c Config) (recoveryKey string, err error) {
	if c.Endpoint == "" || c.Bucket == "" || c.AccessKey == "" || c.SecretKey == "" {
		return "", errors.New("endpoint, bucket, access key and secret key are all required")
	}
	old, ok, err := m.config(ctx)
	if err != nil {
		return "", err
	}
	if ok {
		c.RecoveryKey = old.RecoveryKey
	} else {
		c.RecoveryKey = make([]byte, KeySize)
		rand.Read(c.RecoveryKey)
		recoveryKey = base64.StdEncoding.EncodeToString(c.RecoveryKey)
	}
	b, err := m.open(c)
	if err != nil {
		return "", err
	}
	const probe = ".kayly-setup-check"
	if err := b.Put(ctx, probe, strings.NewReader("ok"), 2); err != nil {
		return "", fmt.Errorf("cannot write to the bucket: %w", err)
	}
	if err := b.Delete(ctx, probe); err != nil {
		return "", fmt.Errorf("cannot delete from the bucket: %w", err)
	}
	raw, _ := json.Marshal(c)
	if err := m.settings.SetSetting(ctx, settingKey, string(raw)); err != nil {
		return "", err
	}
	return recoveryKey, nil
}

// Status is what the owner can see; secrets stay out of it.
type Status struct {
	Configured bool      `json:"configured"`
	Endpoint   string    `json:"endpoint,omitempty"`
	Bucket     string    `json:"bucket,omitempty"`
	LastSync   time.Time `json:"last_sync,omitzero"`
	LastError  string    `json:"last_error,omitempty"`
}

// Status reports the configured bucket and the outcome of the last sync.
func (m *Manager) Status(ctx context.Context) (Status, error) {
	c, ok, err := m.config(ctx)
	if err != nil || !ok {
		return Status{}, err
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	return Status{Configured: true, Endpoint: c.Endpoint, Bucket: c.Bucket, LastSync: m.last, LastError: m.lastErr}, nil
}

// objectKey is where a local backup lives in the bucket.
func objectKey(project, name string) string { return project + "/" + name + ".enc" }

// Sync uploads every local backup the bucket lacks, then applies retention to the bucket.
// Without a configured bucket it does nothing. The owner is told when syncing starts failing
// and when it recovers, not on every attempt.
func (m *Manager) Sync(ctx context.Context) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	c, ok, err := m.config(ctx)
	if err == nil && ok {
		err = m.sync(ctx, c)
	}
	if !ok && err == nil {
		return nil
	}
	m.last = m.now()
	m.lastErr = ""
	if err != nil {
		m.lastErr = err.Error()
	}
	switch {
	case err != nil && !m.failing:
		m.failing = true
		m.say(ctx, "✗ off-site backups failed: %v", err)
	case err == nil && m.failing:
		m.failing = false
		m.say(ctx, "✓ off-site backups work again")
	}
	return err
}

func (m *Manager) say(ctx context.Context, format string, args ...any) {
	if m.notify != nil {
		m.notify(ctx, fmt.Sprintf(format, args...))
	}
}

func (m *Manager) sync(ctx context.Context, c Config) error {
	b, err := m.open(c)
	if err != nil {
		return err
	}
	listed, err := b.List(ctx)
	if err != nil {
		return fmt.Errorf("list bucket: %w", err)
	}
	have := map[string]bool{}
	for _, o := range listed {
		have[o.Key] = true
	}
	var errs []error
	projects, _ := os.ReadDir(m.dir)
	for _, p := range projects {
		files, _ := os.ReadDir(filepath.Join(m.dir, p.Name()))
		for _, f := range files {
			key := objectKey(p.Name(), f.Name())
			if f.IsDir() || strings.HasPrefix(f.Name(), ".") || have[key] {
				continue
			}
			if err := m.upload(ctx, b, c, key, filepath.Join(m.dir, p.Name(), f.Name())); err != nil {
				errs = append(errs, fmt.Errorf("upload %s: %w", key, err))
				continue
			}
			have[key] = true
		}
	}
	// Retention only looks at objects named like backups; anything else in the bucket is
	// not ours to delete.
	var objs []Object
	for k := range have {
		name, isBackup := strings.CutSuffix(k, ".enc")
		_, file, _ := strings.Cut(name, "/")
		if t, err := time.Parse("20060102T150405Z", file[:min(len(file), 16)]); err == nil && isBackup {
			objs = append(objs, Object{Key: k, Name: name, Time: t})
		}
	}
	slices.SortFunc(objs, func(a, b Object) int { return strings.Compare(a.Key, b.Key) })
	for _, o := range Expired(objs, m.now()) {
		if err := b.Delete(ctx, o.Key); err != nil {
			errs = append(errs, fmt.Errorf("delete %s: %w", o.Key, err))
		}
	}
	return errors.Join(errs...)
}

func (m *Manager) upload(ctx context.Context, b Bucket, c Config, key, path string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	fi, err := f.Stat()
	if err != nil {
		return err
	}
	pr, pw := io.Pipe()
	go func() { pw.CloseWithError(Encrypt(pw, f, c.RecoveryKey)) }()
	err = b.Put(ctx, key, pr, EncryptedSize(fi.Size()))
	pr.CloseWithError(err) // unblock the encrypting goroutine if Put gave up early
	return err
}

// Enabled reports whether a bucket is configured.
func (m *Manager) Enabled(ctx context.Context) (bool, error) {
	_, ok, err := m.config(ctx)
	return ok, err
}

// List returns a project's backups in the bucket, newest first.
func (m *Manager) List(ctx context.Context, project string) ([]deploy.Backup, error) {
	c, ok, err := m.config(ctx)
	if err != nil {
		return nil, err
	}
	if !ok {
		return nil, errNotConfigured
	}
	b, err := m.open(c)
	if err != nil {
		return nil, err
	}
	objs, err := b.List(ctx)
	if err != nil {
		return nil, fmt.Errorf("list bucket: %w", err)
	}
	out := []deploy.Backup{}
	for _, o := range objs {
		dir, file, _ := strings.Cut(o.Key, "/")
		name, isBackup := strings.CutSuffix(file, ".enc")
		if dir != project || !isBackup {
			continue
		}
		if t, err := time.Parse("20060102T150405Z", name[:min(len(name), 16)]); err == nil {
			out = append(out, deploy.Backup{Name: name, Size: o.Size, CreatedAt: t})
		}
	}
	slices.SortFunc(out, func(a, b deploy.Backup) int { return strings.Compare(b.Name, a.Name) })
	return out, nil
}

var errNotConfigured = errors.New("off-site backups are not set up")

// Open returns the decrypted contents of a backup in the bucket. A wrong recovery key or a
// damaged object shows up as a read error, so the caller must read to the end.
func (m *Manager) Open(ctx context.Context, project, name string) (io.ReadCloser, error) {
	c, ok, err := m.config(ctx)
	if err != nil {
		return nil, err
	}
	if !ok {
		return nil, errNotConfigured
	}
	b, err := m.open(c)
	if err != nil {
		return nil, err
	}
	return OpenObject(ctx, b, objectKey(project, name), c.RecoveryKey)
}

// OpenObject returns the decrypted contents of one object.
func OpenObject(ctx context.Context, b Bucket, key string, recoveryKey []byte) (io.ReadCloser, error) {
	obj, err := b.Get(ctx, key)
	if err != nil {
		return nil, fmt.Errorf("get %s: %w", key, err)
	}
	pr, pw := io.Pipe()
	go func() {
		pw.CloseWithError(Decrypt(pw, obj, recoveryKey))
		obj.Close()
	}()
	return pr, nil
}
